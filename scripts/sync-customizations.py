#!/usr/bin/env python3
"""Generate the host plugin payloads from the shared sources.

Shared sources (edit these):
    skills/<name>/                 every skill, minus the Codex-only agents/ folder
    policy/universal.md            host-neutral operating rules
    policy/harness-notes.md        notes shared by repository-instruction hosts
    policy/research.md             on-demand research guidance
    copilot-customization/languages/*.md
                                   Copilot-only language instructions
    claude-customization/languages/*.md
                                   Claude-only language rules (workspace install only)
    core/scripts/*.py              hook scripts

Generated (never edit; this script overwrites them):
    copilot-customization/plugin/{skills,scripts,com.github.copilot/rules}
    claude-customization/plugin/{skills,scripts}
    AGENTS.md and .agents/skills/ (Codex and DeepSeek, including agents/ metadata)

Host-specific text lives only in <host>-customization/host-notes.md, and only
where a host has text the others must not receive.

Usage:
    python scripts/sync-customizations.py           # write
    python scripts/sync-customizations.py --check   # exit 1 on drift
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SKILLS = REPO / "skills"
POLICY = REPO / "policy"
SCRIPTS = REPO / "core" / "scripts"
COPILOT = REPO / "copilot-customization"
CLAUDE = REPO / "claude-customization"

SKIP_PARTS = {"__pycache__", "agents"}
BANNER = (
    "<!-- Generated by scripts/sync-customizations.py from policy/ and "
    "the host adapters. Do not edit. -->"
)
WORKSPACE_BANNER = (
    "<!-- Managed by DenisTek SDLC onboarding. "
    "Run aicode.cmd to refresh. -->"
)
AGENTS_BEGIN = "<!-- BEGIN DENISTEK SDLC -->"
AGENTS_END = "<!-- END DENISTEK SDLC -->"
PYTHON_GLOBS = (
    "**/*.py",
    "**/*.pyi",
    "**/*.ipynb",
    "**/pyproject.toml",
    "**/requirements*.txt",
    "**/Pipfile",
    "**/poetry.lock",
    "**/uv.lock",
)
JAVA_GLOBS = (
    "**/*.java",
    "**/pom.xml",
    "**/mvnw",
    "**/mvnw.cmd",
    "**/*.gradle",
    "**/*.gradle.kts",
    "**/gradlew",
    "**/gradlew.bat",
)
COPILOT_RULES = {
    "universal.instructions.md": (
        POLICY / "universal.md",
        "Universal high-priority policy for Copilot-assisted work",
        "**",
        True,
    ),
    "evidence-based-research.instructions.md": (
        POLICY / "research.md",
        "Use when researching external claims, products, standards, prices, limits, "
        "or architecture guidance that affects a software decision.",
        None,
        False,
    ),
    "python.instructions.md": (
        COPILOT / "languages" / "python.md",
        "Use when creating, changing, testing, or reviewing Python files and Python "
        "project configuration.",
        PYTHON_GLOBS,
        False,
    ),
    "java.instructions.md": (
        COPILOT / "languages" / "java.md",
        "Use when creating, changing, testing, or reviewing Java files and Java "
        "build configuration.",
        JAVA_GLOBS,
        False,
    ),
}
# Claude Code loads path-scoped rules from .claude/rules/*.md. The plugin format
# has no rules component, so these are installed into workspaces only.
WORKSPACE_CLAUDE_RULES = {
    "sdlc-python.md": (CLAUDE / "languages" / "python.md", PYTHON_GLOBS),
    "sdlc-java.md": (CLAUDE / "languages" / "java.md", JAVA_GLOBS),
}
WORKSPACE_COPILOT_RULES = {
    "sdlc.instructions.md": "universal.instructions.md",
    "sdlc-python.instructions.md": "python.instructions.md",
    "sdlc-java.instructions.md": "java.instructions.md",
}


def norm(data: bytes) -> bytes:
    return data.replace(b"\r\n", b"\n")


def tree(source: Path, codex: bool = False) -> dict[str, bytes]:
    files: dict[str, bytes] = {}
    for path in sorted(source.rglob("*")):
        relative = path.relative_to(source)
        skip = {"__pycache__"} if codex else SKIP_PARTS
        if path.is_file() and not skip & set(relative.parts):
            files[relative.as_posix()] = norm(path.read_bytes())
    return files


def _copilot_instruction(
    source: Path,
    description: str,
    apply_to: str | tuple[str, ...] | None,
    banner: str,
    notes: str | None = None,
) -> str:
    frontmatter = f'description: "{description}"'
    if isinstance(apply_to, tuple):
        patterns = "\n".join(f'  - "{pattern}"' for pattern in apply_to)
        frontmatter += f"\napplyTo:\n{patterns}"
    elif apply_to:
        frontmatter += f'\napplyTo: "{apply_to}"'
    text = (
        f"---\n{frontmatter}\n---\n\n{banner}\n\n"
        f"{source.read_text(encoding='utf-8').strip()}\n"
    )
    if notes:
        text += f"\n{notes.strip()}\n"
    return text


def _claude_rule(source: Path, paths: tuple[str, ...], banner: str) -> str:
    patterns = "\n".join(f'  - "{pattern}"' for pattern in paths)
    return (
        f"---\npaths:\n{patterns}\n---\n\n{banner}\n\n"
        f"{source.read_text(encoding='utf-8').strip()}\n"
    )


def expected_for_host(plugin: Path, copilot: bool) -> dict[Path, bytes]:
    expected: dict[Path, bytes] = {}
    for skill in sorted(p for p in SKILLS.iterdir() if (p / "SKILL.md").is_file()):
        for relative, data in tree(skill).items():
            expected[plugin / "skills" / skill.name / relative] = data
    for relative, data in tree(SCRIPTS).items():
        expected[plugin / "scripts" / relative] = data
    if copilot:
        notes = norm((COPILOT / "host-notes.md").read_bytes()).decode("utf-8").strip()
        rules = plugin / "com.github.copilot" / "rules"
        for name, (source, description, apply_to, with_notes) in COPILOT_RULES.items():
            text = _copilot_instruction(
                source,
                description,
                apply_to,
                BANNER,
                notes if with_notes else None,
            )
            expected[rules / name] = text.encode("utf-8")
    return expected


def generated_roots(plugin: Path, copilot: bool) -> list[Path]:
    roots = [plugin / "skills", plugin / "scripts"]
    if copilot:
        roots.append(plugin / "com.github.copilot" / "rules")
    return roots


def actual_files(roots: list[Path]) -> dict[Path, bytes]:
    found: dict[Path, bytes] = {}
    for root in roots:
        if root.is_file():
            found[root] = norm(root.read_bytes())
        if root.is_dir():
            for path in root.rglob("*"):
                if path.is_file() and "__pycache__" not in path.parts:
                    found[path] = norm(path.read_bytes())
    return found


def _write_managed_text(path: Path, body: str) -> None:
    managed = f"{AGENTS_BEGIN}\n{body.strip()}\n{AGENTS_END}\n"
    if path.is_file():
        current = path.read_text(encoding="utf-8-sig")
        start = current.find(AGENTS_BEGIN)
        end = current.find(AGENTS_END)
        if (start == -1) != (end == -1):
            raise ValueError(f"Incomplete managed SDLC block in {path}")
        if start != -1:
            end += len(AGENTS_END)
            updated = current[:start] + managed.rstrip() + current[end:]
        else:
            updated = current.rstrip() + "\n\n" + managed
    else:
        updated = managed
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(updated, encoding="utf-8")


def _write_managed_instruction(path: Path, content: str) -> None:
    if path.is_file():
        current = path.read_text(encoding="utf-8-sig")
        if WORKSPACE_BANNER not in current:
            raise ValueError(
                f"Refusing to overwrite unmanaged Copilot instruction: {path}"
            )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _sync_skill_tree(source: Path, destination: Path) -> None:
    expected = tree(source, codex=True)
    if destination.is_dir():
        for path in destination.rglob("*"):
            if path.is_file() and path.relative_to(destination).as_posix() not in expected:
                path.unlink()
    for relative, data in expected.items():
        path = destination / Path(relative)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)


def install_workspace(workspace: Path) -> None:
    destination = workspace.expanduser().resolve()
    if not destination.is_dir():
        raise ValueError(f"Workspace does not exist: {destination}")
    if destination == REPO:
        return

    universal = (POLICY / "universal.md").read_text(encoding="utf-8").strip()
    harness = (POLICY / "harness-notes.md").read_text(encoding="utf-8").strip()
    copilot_notes = (COPILOT / "host-notes.md").read_text(encoding="utf-8").strip()
    claude_notes = (CLAUDE / "host-notes.md").read_text(encoding="utf-8").strip()

    instruction_root = destination / ".github" / "instructions"
    instruction_files = {
        instruction_root / workspace_name: COPILOT_RULES[rule_name]
        for workspace_name, rule_name in WORKSPACE_COPILOT_RULES.items()
    }
    conflicts = [
        path
        for path in instruction_files
        if path.is_file()
        and WORKSPACE_BANNER not in path.read_text(encoding="utf-8-sig")
    ]
    if conflicts:
        raise ValueError(
            "Refusing to overwrite unmanaged Copilot instruction: "
            + ", ".join(str(path) for path in conflicts)
        )
    claude_rules = {
        destination / ".claude" / "rules" / name: _claude_rule(source, paths, WORKSPACE_BANNER)
        for name, (source, paths) in WORKSPACE_CLAUDE_RULES.items()
    }
    claude_conflicts = [
        path
        for path in claude_rules
        if path.is_file()
        and WORKSPACE_BANNER not in path.read_text(encoding="utf-8-sig")
    ]
    if claude_conflicts:
        raise ValueError(
            "Refusing to overwrite unmanaged Claude rule: "
            + ", ".join(str(path) for path in claude_conflicts)
        )
    for path, rule in instruction_files.items():
        source, description, apply_to, with_notes = rule
        content = _copilot_instruction(
            source,
            description,
            apply_to,
            WORKSPACE_BANNER,
            copilot_notes if with_notes else None,
        )
        _write_managed_instruction(path, content)
    for path, content in claude_rules.items():
        _write_managed_instruction(path, content)
    _write_managed_text(
        destination / ".claude" / "CLAUDE.md",
        f"{WORKSPACE_BANNER}\n\n{universal}\n\n{claude_notes}",
    )
    _write_managed_text(
        destination / "AGENTS.md",
        f"{WORKSPACE_BANNER}\n\n{universal}\n\n{harness}",
    )

    for skill in sorted(p for p in SKILLS.iterdir() if (p / "SKILL.md").is_file()):
        for root in (
            destination / ".github" / "skills",
            destination / ".claude" / "skills",
            destination / ".agents" / "skills",
        ):
            _sync_skill_tree(skill, root / skill.name)
    print(f"installed workspace customizations: {destination}")


def sync(check: bool, workspace: Path | None = None) -> int:
    problems: list[str] = []
    targets = []
    for plugin, copilot in ((COPILOT / "plugin", True), (CLAUDE / "plugin", False)):
        targets.append((expected_for_host(plugin, copilot), generated_roots(plugin, copilot)))
    codex_expected = {}
    codex_roots = [REPO / ".agents" / "skills"]
    for skill in sorted(p for p in SKILLS.iterdir() if (p / "SKILL.md").is_file()):
        destination = REPO / ".agents" / "skills" / skill.name
        for relative, data in tree(skill, codex=True).items():
            codex_expected[destination / relative] = data
    instructions = REPO / "AGENTS.md"
    codex_roots.append(instructions)
    codex_expected[instructions] = (
        "<!-- Generated by scripts/sync-customizations.py from policy/universal.md "
        "and policy/harness-notes.md. Edit those files, not this one. -->\n\n"
        + (POLICY / "universal.md").read_text(encoding="utf-8").strip()
        + "\n\n" + (POLICY / "harness-notes.md").read_text(encoding="utf-8").strip()
        + "\n"
    ).encode("utf-8")
    targets.append((codex_expected, codex_roots))
    for expected, roots in targets:
        actual = actual_files(roots)
        for path in sorted(actual.keys() - expected.keys()):
            problems.append(f"stale   {path.relative_to(REPO)}")
            if not check:
                path.unlink()
        for path, data in sorted(expected.items()):
            if actual.get(path) != data:
                problems.append(
                    f"{'missing' if path not in actual else 'differs'} "
                    f"{path.relative_to(REPO)}"
                )
                if not check:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_bytes(data)
        if not check:
            for root in roots:
                for directory in sorted(root.rglob("*"), reverse=True):
                    if directory.is_dir() and not any(directory.iterdir()):
                        shutil.rmtree(directory)
    verb = "drift" if check else "updated"
    for line in problems:
        print(f"{verb}: {line}")
    if check and problems:
        print("Run: python scripts/sync-customizations.py", file=sys.stderr)
        return 1
    if not check and workspace is not None:
        install_workspace(workspace)
    print("in sync" if not problems else f"{len(problems)} file(s) {verb}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="report drift only")
    parser.add_argument(
        "--workspace",
        type=Path,
        help="Install current managed customizations into this project.",
    )
    args = parser.parse_args()
    if args.check and args.workspace:
        parser.error("--workspace cannot be combined with --check")
    return sync(args.check, args.workspace)


if __name__ == "__main__":
    raise SystemExit(main())
